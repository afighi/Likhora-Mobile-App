/**
 * Business profiles — what makes onboarding ask the RIGHT questions.
 *
 * The first version of onboarding assumed every user was selling goods from a
 * storefront: it asked about spoilage and wholesale suppliers, and generated a
 * roadmap ending in "Storefront Display Signage". That is wrong for a whole
 * class of Filipino micro-businesses — a pet groomer, a laundry, a repair
 * shop and a salon sell LABOUR, not merchandise. They have no wholesale
 * supplier to canvass and nothing to put a price tag on.
 *
 * Each profile below owns the parts of onboarding that genuinely differ by
 * business type: who the customers are, what can realistically go wrong, which
 * permits apply, the extra questions worth asking, and the two roadmap tasks
 * that are about actually running the thing. The universal Philippine
 * registration steps (Barangay → DTI → Mayor → BIR → SSS/PhilHealth/Pag-IBIG)
 * stay shared, because those are the same whatever you sell.
 *
 * A custom business type gets the same shape generated by Khora AI — see
 * services/onboardingAdvisor.ts.
 */

export interface RiskOption {
  risk: string;
  contingency: string;
}

export interface ExtraQuestion {
  id: string;
  label: string;
  type: 'choice' | 'text';
  options?: string[];
  placeholder?: string;
}

/** A roadmap task before it is bound to a user id and step number. */
export interface TaskBlueprint {
  title: string;
  desc: string;
  category: string;
  agency: string;
  legal_basis: string;
  estimated_time: string;
  estimated_cost: string;
  required_docs: string[];
  sub_steps: string[];
}

export interface BusinessProfile {
  id: string; // stored verbatim in profiles.business_type
  label: string;
  desc: string;
  iconName: 'store' | 'utensils' | 'globe' | 'wrench' | 'shopping-bag' | 'plus-circle';

  /** False for labour/service businesses — drives wording, not just content. */
  isProductBased: boolean;

  customerSegments: string[];
  differentiatorPlaceholder: string;
  researchStages: { id: string; label: string }[];
  risks: RiskOption[];
  permits: string[];
  extraQuestions: ExtraQuestion[];

  /** Replaces the old one-size-fits-all "Source Wholesale Goods" task. */
  operationsTask: TaskBlueprint;
  /** Replaces the old "Storefront Display Signage" task. */
  launchTask: TaskBlueprint;
}

